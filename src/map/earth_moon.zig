/// CalcSine (field.asm @90d0): (Mode7SineTbl[angle&$7f] * $ad) >> 8, negate if angle bit7.
pub fn calcSine(angle: u8, zoom_ad: u8) i32 {
    const sine: u32 = mode7_sine_tbl[angle & 0x7f];
    const prod: u32 = sine * zoom_ad;
    var y: i32 = @intCast(prod >> 8);
    if ((angle & 0x80) != 0) y = -y;
    return y;
}

/// CalcMode7Rot (@90ba) → M7A/D=cos, M7B=sin, M7C=-sin (×zoom via $ad).
/// UpdateMode7Regs (@9104): write $6e/$6f→M7A+M7D, $70/$71→M7B, $72/$73→M7C.
pub const Mode7Matrix = struct { a: i32, b: i32, c: i32, d: i32 };

pub fn calcMode7Rot(angle: u8, zoom_ad: u8) Mode7Matrix {
    const cos = calcSine(0x40 +% angle, zoom_ad);
    const sin = calcSine(angle, zoom_ad);
    const nsin = calcSine(0x80 +% angle, zoom_ad);
    return .{ .a = cos, .b = sin, .c = nsin, .d = cos };
}

/// Star-travel `_00a465` zeros `$70–$73` (M7B/M7C) — pure scale M7A=M7D=`$6e`.
pub fn starTravelMatrix(zoom_6e: u8) Mode7Matrix {
    const z: i32 = zoom_6e;
    return .{ .a = z, .b = 0, .c = 0, .d = z };
}

/// Decode 8 planet tiles (4bpp × 32) + 16-color SNES pal into ready blit data.
pub const PlanetSprites = struct {
    tiles: [8][64]u8 = undefined,
    palette: [16]snes.Color = undefined,

    pub fn load(self: *PlanetSprites) void {
        var t: usize = 0;
        while (t < 8) : (t += 1) {
            const raw = earth_moon_gfx[t * 32 ..][0..32];
            snes.decodeTile4bpp(raw, &self.tiles[t]);
        }
        var i: usize = 0;
        while (i < 16) : (i += 1) {
            const w = @as(u16, earth_moon_pal[i * 2]) | (@as(u16, earth_moon_pal[i * 2 + 1]) << 8);
            self.palette[i] = snes.Color.fromSnes(w);
            self.palette[i].a = 255;
            if (i == 0) self.palette[0].a = 0;
        }
    }

    /// Draw 16×16 planet (2×2 tiles) at center, nearest-neighbor scaled to `size` px.
    pub fn blitPlanet(
        self: *const PlanetSprites,
        dest: []u8,
        dest_w: usize,
        dest_h: usize,
        cx: i32,
        cy: i32,
        size: i32,
        to_moon: bool,
    ) void {
        if (size < 2) return;
        const base: usize = if (to_moon) 4 else 0;
        // Source is 16×16 composed of tiles base..base+3 (TL TR BL BR).
        const half = @divTrunc(size, 2);
        var py: i32 = 0;
        while (py < size) : (py += 1) {
            var px: i32 = 0;
            while (px < size) : (px += 1) {
                const sx = @divTrunc(px * 16, size);
                const sy = @divTrunc(py * 16, size);
                const tile_i: usize = base + @as(usize, @intCast(@divTrunc(sx, 8))) + @as(usize, @intCast(@divTrunc(sy, 8))) * 2;
                const lx: usize = @intCast(sx & 7);
                const ly: usize = @intCast(sy & 7);
                const idx = self.tiles[tile_i][ly * 8 + lx];
                if (idx == 0) continue;
                const dx = cx - half + px;
                const dy = cy - half + py;
                if (dx < 0 or dy < 0 or dx >= @as(i32, @intCast(dest_w)) or dy >= @as(i32, @intCast(dest_h))) continue;
                const c = self.palette[idx & 0x0f];
                const o = (@as(usize, @intCast(dy)) * dest_w + @as(usize, @intCast(dx))) * 4;
                if (o + 3 >= dest.len) continue;
                dest[o] = c.r;
                dest[o + 1] = c.g;
                dest[o + 2] = c.b;
                dest[o + 3] = 255;
            }
        }
    }
};

/// DrawStars (@a57e) — star field from a field-style RNG seed (re-seeded each call).
pub fn drawStars(dest: []u8, dest_w: usize, dest_h: usize, seed: u32, count: usize) void {
    const colors = [_][3]u8{
        .{ 255, 255, 255 },
        .{ 200, 220, 255 },
        .{ 255, 240, 200 },
        .{ 180, 200, 255 },
        .{ 255, 255, 220 },
        .{ 160, 180, 255 },
        .{ 255, 200, 200 },
        .{ 220, 220, 255 },
    };
    var rng = seed;
    var n: usize = 0;
    while (n < count) : (n += 1) {
        rng = rng *% 1664525 +% 1013904223;
        const x: usize = (rng >> 16) % dest_w;
        rng = rng *% 1664525 +% 1013904223;
        const y: usize = (rng >> 16) % dest_h;
        rng = rng *% 1664525 +% 1013904223;
        const attr: u8 = @truncate(rng >> 24);
        const ci = (attr >> 1) & 7;
        const c = colors[ci];
        const o = (y * dest_w + x) * 4;
        if (o + 3 >= dest.len) continue;
        dest[o] = c[0];
        dest[o + 1] = c[1];
        dest[o + 2] = c[2];
        dest[o + 3] = 255;
        if ((attr & 1) != 0 and x + 1 < dest_w) {
            const o2 = o + 4;
            if (o2 + 3 < dest.len) {
                dest[o2] = c[0];
                dest[o2 + 1] = c[1];
                dest[o2 + 2] = c[2];
                dest[o2 + 3] = 255;
            }
        }
    }
}

/// Mode-7 zoom parameter `$6e` during _00a465 star travel: `($79>>2)+9`.
pub fn starTravelZoom(timer_79: u8) u8 {
    return (timer_79 >> 2) +% 9;
}

