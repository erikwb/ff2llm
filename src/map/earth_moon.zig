/// WH0/WH1 for scanline `scan_y` (0..223). `dh` kept for API compatibility.
pub fn telescopeWindowLR(scan_y: i32, dh: i32) struct { l: i32, r: i32 } {
    _ = dh;
    if (scan_y < 0 or scan_y >= @as(i32, @intCast(telescope_window_lr.len))) return .{ .l = 255, .r = 0 };
    const e = telescope_window_lr[@intCast(scan_y)];
    return .{ .l = e[0], .r = e[1] };
}

test "telescope ROM LUT mid open edges closed" {
    // ROM TelescopeWindowData: closed top, open mid (y115 → 64,192), closed bottom.
    const top = telescopeWindowLR(0, 224);
    try std.testing.expectEqual(@as(i32, 0xFF), top.l);
    try std.testing.expectEqual(@as(i32, 0x00), top.r);
    const mid = telescopeWindowLR(115, 224);
    try std.testing.expectEqual(@as(i32, 64), mid.l);
    try std.testing.expectEqual(@as(i32, 192), mid.r);
    const bot = telescopeWindowLR(200, 224);
    try std.testing.expectEqual(@as(i32, 0xFF), bot.l);
    // Open span ~y57..182
    const open_edge = telescopeWindowLR(57, 224);
    try std.testing.expect(open_edge.l < open_edge.r);
}

