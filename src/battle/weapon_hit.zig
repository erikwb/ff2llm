/// Slice for frame id 0..34 (terminator $ff included).
pub fn hitFrame(id: u8) []const u8 {
    if (id >= weapon_hit_frame_count) return &[_]u8{0xFF};
    const start: usize = weapon_hit_frame_off[id];
    var end = start;
    while (end < weapon_hit_frame_data.len) : (end += 1) {
        if (weapon_hit_frame_data[end] == 0xFF) {
            return weapon_hit_frame_data[start .. end + 1];
        }
    }
    return weapon_hit_frame_data[start..];
}

/// DrawWeaponHit position math (sprite.asm @e698).
/// base = (hit_x - $18, hit_y - $18); sprite at (base_x + (pos>>4)*8, base_y + (pos&$0f)*8).
pub fn spriteXY(hit_x: i32, hit_y: i32, pos: u8) struct { x: i32, y: i32 } {
    const bx = hit_x - 0x18;
    const by = hit_y - 0x18;
    const ox: i32 = @as(i32, pos >> 4) * 8;
    const oy: i32 = @as(i32, pos & 0x0f) * 8;
    return .{ .x = bx + ox, .y = by + oy };
}

const rom_mod = @import("../rom.zig");
const snes = @import("../gfx/snes.zig");

/// WeaponGfx @ SNES $1C/D900.
const weapon_gfx_cpu: u24 = 0x1CD900;
/// WeaponAnimProp @ $0F/9E10 (btlgfx_data.asm) — 4 bytes/item, file 0x79E10.
const weapon_anim_prop_file: usize = 0x79E10;
/// AnimPal @ $0E/CB00 → file 0x74B00 (16 bytes / row = 8 SNES colors).
const anim_pal_file: usize = 0x74B00;
/// WeaponTileOffsetTbl (@fb57) — LoadHitGfx index → tile count base * $18.
pub const weapon_tile_offset_tbl = [_]u8{
    0x98, 0x98, 0x98, 0xA6, 0xB0, 0xBA, 0xC4, 0xD0, 0x64, 0x68, 0x6C, 0x70, 0x74, 0x78, 0x7C, 0x80,
    0x84, 0x88, 0x8C, 0x90, 0x94, 0x0C,
};

const hit_tile_count: usize = 16;
const bytes_per_3bpp: usize = 24;

/// WeaponAnimProp entry (LoadWeaponAnim @d8bd).
/// +0 pal row (LoadWeaponPal → AnimPal), +1 weapon gfx, +2 hit type, +3 anim type.
pub const WeaponAnimProp = struct {
    pal: u8 = 0,
    gfx: u8 = 0,
    hit: u8 = 0,
    anim: u8 = 0,

    pub fn load(r: *const rom_mod.Rom, item_id: u8) WeaponAnimProp {
        const off = weapon_anim_prop_file + @as(usize, item_id) * 4;
        const raw = r.slice(off, 4) catch return .{};
        return .{
            .pal = raw[0],
            .gfx = raw[1],
            .hit = raw[2],
            .anim = raw[3],
        };
    }
};

/// DrawWeaponHit `$f0c7` size mode (sprite.asm @e643).
pub const HitSpriteMode = enum(u8) {
    /// $00 — small 8×8 OAM entries.
    small = 0,
    /// $ff — large 16×16 OAM entries (tile N + N+1 + N+16 + N+17).
    large = 0xFF,
    /// $fe — harp: large + CopyHarpSpriteFlags (same 16×16 blit for host).
    harp = 0xFE,
    _,
};

/// Loaded hit CHR (LoadHitGfx) + LoadWeaponPal colors from AnimPal.
pub const HitGfx = struct {
    tiles: [hit_tile_count][64]u8 = undefined,
    palette: [8]snes.Color = undefined,
    loaded: bool = false,
    /// SwordWhipHitFrameTbl row (= Prop+2 when ≤7 for sword/whip path).
    frame_row: u8 = 0,
    /// Prop+3 anim type (WeaponAnimTbl index).
    anim_type: u8 = 0,
    /// `$f0c7` — small / large / harp.
    sprite_mode: HitSpriteMode = .small,

    /// LoadHitGfx(hit_type) + LoadWeaponPal(pal_idx). Defaults: type 0, pal row $25.
    pub fn load(self: *HitGfx, r: *const rom_mod.Rom, hit_type: u8) void {
        self.loadWithPal(r, hit_type, 0x25, 0);
    }

    pub fn loadWithPal(self: *HitGfx, r: *const rom_mod.Rom, hit_type: u8, pal_idx: u8, anim_type: u8) void {
        const idx: usize = @min(@as(usize, hit_type), weapon_tile_offset_tbl.len - 1);
        const tile_base: usize = weapon_tile_offset_tbl[idx];
        const file_off = rom_mod.Rom.loromOffset(weapon_gfx_cpu) + tile_base * bytes_per_3bpp;
        const nbytes = hit_tile_count * bytes_per_3bpp;
        const gfx = r.slice(file_off, nbytes) catch {
            self.loaded = false;
            return;
        };
        var t: usize = 0;
        while (t < hit_tile_count) : (t += 1) {
            decode3bpp(gfx[t * bytes_per_3bpp ..][0..bytes_per_3bpp], &self.tiles[t]);
        }
        // LoadWeaponPal: AnimPal[pal_idx] × 16 bytes → 8 colors (weapon.asm @d8a0).
        const pal_off = anim_pal_file + @as(usize, pal_idx) * 16;
        if (r.slice(pal_off, 16)) |pr| {
            var i: usize = 0;
            while (i < 8) : (i += 1) {
                const w = @as(u16, pr[i * 2]) | (@as(u16, pr[i * 2 + 1]) << 8);
                self.palette[i] = snes.Color.fromSnes(w);
                self.palette[i].a = 255;
            }
            self.palette[0].a = 0;
        } else |_| {
            const pal_words = [_]u16{ 0x0000, 0x7FFF, 0x7FF4, 0x7FE0, 0x7F00, 0x7C00, 0x5400, 0x2800 };
            var i: usize = 0;
            while (i < 8) : (i += 1) {
                self.palette[i] = snes.Color.fromSnes(pal_words[i]);
                self.palette[i].a = 255;
            }
            self.palette[0].a = 0;
        }
        // SwordWhipHitFrameTbl row from hit type when in range (sword path uses $53).
        self.frame_row = if (hit_type < 8) hit_type else 0;
        self.anim_type = anim_type;
        // Harp anim $08 → $fe; bow/claw-ish large projectile paths often $ff.
        self.sprite_mode = switch (anim_type) {
            0x08 => .harp, // harp
            0x04, 0x05 => .large, // bow / unarmed bow path
            else => .small,
        };
        self.loaded = true;
    }

    /// Load from equipped weapon item id via WeaponAnimProp.
    pub fn loadForWeapon(self: *HitGfx, r: *const rom_mod.Rom, item_id: u8) void {
        if (item_id == 0) {
            self.load(r, 0);
            return;
        }
        const prop = WeaponAnimProp.load(r, item_id);
        self.loadWithPal(r, prop.hit, prop.pal, prop.anim);
    }

    /// DrawWeaponHit (sprite.asm @e63d) for one frame id at impact (hit_x, hit_y).
    /// `tile_base` is $f0c6 (usually 0 when hit CHR is isolated bank).
    pub fn drawFrame(
        self: *const HitGfx,
        dest: []u8,
        dest_w: usize,
        hit_x: i32,
        hit_y: i32,
        frame_id: u8,
        tile_base: u8,
        hflip: bool,
    ) void {
        if (!self.loaded) return;
        const large = self.sprite_mode == .large or self.sprite_mode == .harp;
        const data = hitFrame(frame_id);
        var i: usize = 0;
        while (i + 1 < data.len) : (i += 2) {
            if (data[i] == 0xFF) break;
            const pos = data[i];
            const tile_off = data[i + 1];
            const xy = spriteXY(hit_x, hit_y, pos);
            const ti: usize = @as(usize, tile_base) +% tile_off;
            if (ti >= hit_tile_count) continue;
            if (large) {
                // 16×16 large OAM: tiles ti, ti+1, ti+16, ti+17 (when in bank).
                blit8(dest, dest_w, xy.x, xy.y, &self.tiles[ti], &self.palette, hflip);
                if (ti + 1 < hit_tile_count)
                    blit8(dest, dest_w, xy.x + 8, xy.y, &self.tiles[ti + 1], &self.palette, hflip);
                if (ti + 16 < hit_tile_count)
                    blit8(dest, dest_w, xy.x, xy.y + 8, &self.tiles[ti + 16], &self.palette, hflip);
                if (ti + 17 < hit_tile_count)
                    blit8(dest, dest_w, xy.x + 8, xy.y + 8, &self.tiles[ti + 17], &self.palette, hflip);
            } else {
                blit8(dest, dest_w, xy.x, xy.y, &self.tiles[ti], &self.palette, hflip);
            }
        }
    }
};

/// Frame index from SwordWhipHitFrameTbl for weapon row and time step 0..7.
/// `$20` means no draw this step.
pub fn swordWhipFrame(row: u8, step: u8) u8 {
    const r: usize = @min(@as(usize, row), 7);
    const c: usize = @min(@as(usize, step), 7);
    return sword_whip_hit_frame_tbl[r][c];
}

test "swordWhipFrame row0 step2 is first visible frame" {
    // Row 0: $20,$20,$00,$01,$02,$03,$04,$20
    try std.testing.expectEqual(@as(u8, 0x20), swordWhipFrame(0, 0));
    try std.testing.expectEqual(@as(u8, 0x00), swordWhipFrame(0, 2));
    try std.testing.expectEqual(@as(u8, 0x04), swordWhipFrame(0, 6));
}

