fn decode3bpp(tile: *const [24]u8, out: *[64]u8) void {
    var row: usize = 0;
    while (row < 8) : (row += 1) {
        const p0 = tile[row * 2];
        const p1 = tile[row * 2 + 1];
        const p2 = tile[16 + row];
        var col: usize = 0;
        while (col < 8) : (col += 1) {
            const bit: u3 = @intCast(7 - col);
            out[row * 8 + col] =
                ((p0 >> bit) & 1) |
                (((p1 >> bit) & 1) << 1) |
                (((p2 >> bit) & 1) << 2);
        }
    }
}

fn blit8(
    dest: []u8,
    dest_w: usize,
    dx: i32,
    dy: i32,
    tile: *const [64]u8,
    palette: *const [8]snes.Color,
    hflip: bool,
) void {
    var y: i32 = 0;
    while (y < 8) : (y += 1) {
        var x: i32 = 0;
        while (x < 8) : (x += 1) {
            const sx: usize = if (hflip) @intCast(7 - x) else @intCast(x);
            const idx = tile[@as(usize, @intCast(y)) * 8 + sx];
            if (idx == 0) continue;
            const c = palette[idx & 7];
            const px = dx + x;
            const py = dy + y;
            if (px < 0 or py < 0) continue;
            const o: usize = @as(usize, @intCast(py * @as(i32, @intCast(dest_w)) + px)) * 4;
            if (o + 3 >= dest.len) continue;
            dest[o] = c.r;
            dest[o + 1] = c.g;
            dest[o + 2] = c.b;
            dest[o + 3] = 255;
        }
    }
}
